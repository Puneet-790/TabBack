export type EmailPolicyResult = { ok: true } | { ok: false; error: string };

const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;

function normalizeDomain(email: string): string {
  return email.trim().toLowerCase().split("@").pop() ?? "";
}

// Strong markers match anywhere in the domain; weaker ones require a word boundary
const DISPOSABLE_MARKERS = new RegExp(
  [
    "temp-?mail|mailinator|yopmail|guerrilla-?mail|trash-?mail|10-?minute-?mail|1-?sec-?mail|throw-?away",
    "(?:^|[.-])dispos(?:able|post)(?:[.-]|$)",
    "(?:^|[.-])(?:fake-?mail|spamgourmet|sharklasers|mintemail|maildrop|dodgit|mailnesia|emailnator|mohmal|dropmail|discard-?mail|tempr-?mail|tempmailbox|tmail|mailtemp|spam(?:box|goes|in|slicer|waste|spot|l))(?:[.-]|$)",
  ].join("|"),
  "i",
);

export function isDisposableEmail(email: string): boolean {
  const domain = normalizeDomain(email);
  if (domain.length === 0) return false;
  if (DISPOSABLE_DOMAINS.has(domain)) return true;
  const parts = domain.split(".");
  for (let i = 1; i < parts.length - 1; i++) {
    const suffix = parts.slice(i).join(".");
    if (DISPOSABLE_DOMAINS.has(suffix)) return true;
  }
  return DISPOSABLE_MARKERS.test(domain);
}

export function validateEmailForSignup(email: string): EmailPolicyResult {
  const trimmed = email.trim();
  if (!EMAIL_PATTERN.test(trimmed)) {
    return { ok: false, error: "Enter a valid email address." };
  }
  if (isDisposableEmail(trimmed)) {
    return {
      ok: false,
      error: "Disposable email addresses aren't allowed. Use a personal email like Gmail, Outlook or Yahoo.",
    };
  }
  return { ok: true };
}